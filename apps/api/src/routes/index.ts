import { Router } from 'express';
import * as auth from '../controllers/auth.controller.ts';
import * as requests from '../controllers/request.controller.ts';
import * as account from '../controllers/account.controller.ts';
import { authenticated, verified, admin } from '../middleware/auth.ts';
import { limit } from '../middleware/rate-limit.ts';

export const router = Router();
router.get('/auth/session', auth.session);
router.post('/auth/register', limit('register', 5, 3600), auth.register);
router.post('/auth/login', limit('login', 15, 900), auth.login);
router.post('/auth/forgot', limit('forgot', 5, 3600), auth.forgot);
router.post('/auth/reset', limit('reset', 10, 3600), auth.reset);
router.post('/auth/verify', limit('verify', 30, 900), auth.verify);
router.post('/auth/resend-otp', limit('resend-otp', 10, 3600), auth.resend);
router.post('/auth/logout', authenticated, auth.logout);
router.use(authenticated);
router.get('/profile/donor', account.getDonor);
router.put('/profile', account.saveProfile);
router.put('/profile/donor', account.saveDonor);
router.get('/requests', requests.list);
router.post('/requests', limit('create', 10, 3600), requests.create);
router.get('/requests/:id', requests.detail);
router.patch('/requests/:id', requests.edit);
router.delete('/requests/:id', requests.remove);
router.post('/requests/:id/publish', verified, limit('publish', 10, 3600), requests.publish);
router.post('/requests/:id/close', requests.close);
router.post('/requests/:id/retry', requests.retry);
router.post('/requests/:id/offers', verified, limit('offer', 30, 3600), requests.offer);
router.post('/requests/:id/offers/:offerId/confirm', verified, requests.confirm);
router.post('/requests/:id/offers/:offerId/withdraw', requests.withdraw);
router.post('/commitments/:id/cancel', requests.cancel);
router.post('/commitments/:id/share', requests.share);
router.get('/participation', requests.mine);
router.get('/notifications', account.notifications);
router.post('/notifications/:id/read', account.read);
router.get('/invitations', account.invitations);
router.post('/invitations/:id/decline', account.decline);
router.post('/requests/:id/report', limit('report', 10, 3600), account.report);
router.get('/admin', admin, account.adminOverview);
router.post('/admin/reports/:id', admin, account.resolveReport);
